"""Generate ``src/model/unicode_tables.rs`` from the running Python's Unicode data.

The ported text handling must equal Python's character for character (ADR-0013 §2):
tag and card-name normalization (``" ".join(s.split()).casefold()``), the rule-language
lexer and the decklist parser (``re``'s ``\\s``, ``\\d`` and ``int()``, ``(?i)``,
``str.splitlines``), and error messages (``repr``). Rust's standard library defines
none of these the way Python does, so every table is taken from Python itself.

Usage:  python native/core/tools/gen_unicode.py [--check]

``--check`` exits non-zero if the committed file differs from what this Python would
generate (run by tests/web/test_unicode_tables.py when the Unicode versions match).
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "model" / "unicode_tables.rs"


def _rust_char(c: str) -> str:
    return f"'\\u{{{ord(c):x}}}'"


def _rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def render() -> str:
    """The Rust source for the current Python's Unicode version."""
    chars = [chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]
    spaces = [c for c in chars if c.isspace()]
    folds = [(c, c.casefold()) for c in chars if c.casefold() != c]
    digits = [(c, int(c)) for c in chars if re.fullmatch(r"\d", c)]
    breaks = [c for c in chars if len(("a" + c + "b").splitlines()) == 2]
    # Printable characters as inclusive ranges (repr escapes everything else).
    printable: list[tuple[int, int]] = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF or not chr(code).isprintable():
            continue
        if printable and printable[-1][1] == code - 1:
            printable[-1] = (printable[-1][0], code)
        else:
            printable.append((code, code))
    # Non-ASCII characters that re's (?i) matches with an ASCII letter.
    letters = "abcdefghijklmnopqrstuvwxyz"
    ignorecase = [
        (c, letter)
        for letter in letters
        for c in chars
        if ord(c) > 127 and re.fullmatch("(?i)" + letter, c)
    ]
    lines = [
        "//! Unicode tables generated by `native/core/tools/gen_unicode.py`. Do not edit.",
        "//!",
        f"//! Source: Python's `unicodedata`, Unicode {unicodedata.unidata_version}.",
        "",
        "/// The Unicode version the tables were generated from.",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Characters for which Python's `str.isspace()` is true (what `str.split()` splits on).",
        "pub static WHITESPACE: &[char] = &[",
        *(f"    {_rust_char(c)}," for c in spaces),
        "];",
        "",
        "/// Python's `str.casefold()` for every character it changes, sorted by character.",
        "pub static CASEFOLD: &[(char, &str)] = &[",
        *(f"    ({_rust_char(c)}, {_rust_str(f)})," for c, f in folds),
        "];",
        "",
        "/// Characters `re`'s `\\d` matches, with the value `int()` gives them, sorted.",
        "pub static DIGITS: &[(char, u8)] = &[",
        *(f"    ({_rust_char(c)}, {v})," for c, v in digits),
        "];",
        "",
        "/// Characters at which `str.splitlines()` breaks (besides the pair `\\r\\n`).",
        "pub static LINE_BREAKS: &[char] = &[",
        *(f"    {_rust_char(c)}," for c in breaks),
        "];",
        "",
        "/// Code points for which `str.isprintable()` is true, as sorted inclusive ranges.",
        "pub static PRINTABLE: &[(u32, u32)] = &[",
        *(f"    (0x{a:x}, 0x{b:x})," for a, b in printable),
        "];",
        "",
        "/// Non-ASCII characters that `re`'s `(?i)` matches with an ASCII letter.",
        "pub static IGNORECASE_EXTRA: &[(char, char)] = &[",
        *(f"    ({_rust_char(c)}, {_rust_char(letter)})," for c, letter in ignorecase),
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
